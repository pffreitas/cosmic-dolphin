import React from "react";
import { act, renderHook, waitFor } from "@testing-library/react-native";
import AsyncStorage from "@react-native-async-storage/async-storage";
import { AppState, type AppStateStatus } from "react-native";
import { CaptureProvider, useCaptures } from "../CaptureContext";
import { useAuth } from "../AuthContext";
import { MobileAPI } from "@/lib/mobile-api";
jest.mock("../AuthContext", () => ({ useAuth: jest.fn() }));
jest.mock("@/lib/mobile-api", () => ({ MobileAPI: { create: jest.fn() } }));
jest.mock("expo-crypto", () => ({ randomUUID: () => require("crypto").randomUUID() }));
let mockNative: unknown[] = [];
const mockBridge = { readPendingShares: jest.fn(async () => JSON.stringify(mockNative)), removePendingShares: jest.fn(async (ids: string[]) => { mockNative = mockNative.filter((value: any) => !ids.includes(value.id)); }) };
jest.mock("../../modules/share-queue", () => ({ pendingShares: () => mockBridge }));
const wrapper = ({ children }: { children: React.ReactNode }) => <CaptureProvider>{children}</CaptureProvider>;
const incoming = { id: "native-arrival", url: "https://example.com/native", userId: "reader", queuedAt: "2026-11-09T12:00:00Z" };
beforeEach(async () => {
  await AsyncStorage.clear(); jest.clearAllMocks(); mockNative = [incoming];
  (useAuth as jest.Mock).mockReturnValue({ user: { id: "reader" } });
  (MobileAPI.create as jest.Mock).mockResolvedValue({ bookmark: { id: "saved", userId: "reader" }, alreadySaved: false });
});
it("imports the group queue on app launch before matching-account drain", async () => {
  const { result } = renderHook(() => useCaptures(), { wrapper });
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(1));
  await waitFor(() => expect(result.current.captures[0].status).toBe("saved"));
  expect(mockNative).toEqual([]);
  expect(MobileAPI.create).toHaveBeenCalledWith(expect.objectContaining({ sourceUrl: incoming.url, queuedAt: new Date(incoming.queuedAt), captureSource: "ios_share_extension", capturePlatform: "ios" }), expect.anything(), "reader");
});
it("durably imports while signed out and waits for the owning account after sign-in", async () => {
  (useAuth as jest.Mock).mockReturnValue({ user: null });
  const { result, rerender } = renderHook(() => useCaptures(), { wrapper });
  await waitFor(() => expect(mockBridge.removePendingShares).toHaveBeenCalledWith([incoming.id]));
  expect(result.current.captures).toEqual([]);
  expect(MobileAPI.create).not.toHaveBeenCalled();
  (useAuth as jest.Mock).mockReturnValue({ user: { id: "other" } });
  rerender(undefined);
  await act(async () => { await result.current.drain(); });
  expect(MobileAPI.create).not.toHaveBeenCalled();
  (useAuth as jest.Mock).mockReturnValue({ user: { id: "reader" } });
  rerender(undefined);
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(1));
});
it("imports a new extension arrival on foreground before replaying it", async () => {
  let foreground: ((state: AppStateStatus) => void) | undefined;
  jest.spyOn(AppState, "addEventListener").mockImplementation((_event, listener) => { foreground = listener; return { remove: jest.fn() }; });
  const { result } = renderHook(() => useCaptures(), { wrapper });
  await waitFor(() => expect(result.current.captures[0].status).toBe("saved"));
  mockNative = [{ ...incoming, id: "foreground-arrival", url: "https://example.com/foreground" }];
  act(() => foreground!("active"));
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(2));
  expect(mockNative).toEqual([]);
  jest.restoreAllMocks();
});
it("coalesces overlapping foreground work and sends only fresh arrivals after a failed request", async () => {
  let foreground: ((state: AppStateStatus) => void) | undefined;
  jest.spyOn(AppState, "addEventListener").mockImplementation((_event, listener) => { foreground = listener; return { remove: jest.fn() }; });
  let reject!: (error: Error) => void;
  (MobileAPI.create as jest.Mock).mockImplementationOnce(() => new Promise((_resolve, fail) => { reject = fail; }));
  const { result } = renderHook(() => useCaptures(), { wrapper });
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(1));
  mockNative = [{ ...incoming, id: "arrived-while-saving", url: "https://example.com/fresh" }];
  act(() => foreground!("active"));
  await act(async () => { reject(new Error("Offline")); });
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(2));
  expect(result.current.captures.find(value => value.id === incoming.id)?.status).toBe("failed");
  expect(MobileAPI.create).toHaveBeenNthCalledWith(2, expect.objectContaining({ sourceUrl: "https://example.com/fresh" }), expect.anything(), "reader");
  expect(mockNative).toEqual([]);
  act(() => result.current.retry(incoming.id));
  await waitFor(() => expect(MobileAPI.create).toHaveBeenCalledTimes(3));
  jest.restoreAllMocks();
});
